#!/usr/bin/env python3
"""Import three published OutFox Serenity recordings and Beginner charts."""

import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from fractions import Fraction
from pathlib import Path
from urllib.parse import quote
from urllib.request import urlopen


ROOT = Path(__file__).resolve().parent.parent
REPOSITORY = 'TeamRizu/OutFox-Serenity'
REVISION = '8eba95639e5b3f789c7cd5c923080f43cf792907'  # v2.5 release
CHART_CREDIT = 'Daniel Rotwind'
CHART_LICENSE = 'https://creativecommons.org/licenses/by/4.0/'
CHART_TERMS = 'https://projectoutfox.com/outfox-serenity/outfox-serenity-templates'
SAMPLE_RATE = 44100
PREVIEW_SECONDS = 8
TRACK_BITRATE = '64k'
PREVIEW_BITRATE = '48k'
LANES = {0: 'dodge-left', 2: 'jump', 3: 'dodge-right'}  # SSC dance L,D,U,R
SOURCES = (
    ('beatucada', '2', 'Kurio Prokos', 'Beatucada', 'credits.txt', 'Kurio Prokos', 'by-sa',
     'e0b1c65bbfa578e960cc9ce64dfaf777de34ad50b3bd1b5084537cb1e9054117',
     '64e41a978474bb4be9e0cc7beed9fb41ea5b679325efcb229e51943d26436be5'),
    ('into-my-dream', '2', 'Lagoona', 'Into My Dream', 'credits.txt', 'Lagoona / Andreas Viklund', 'by',
     'b388c8ca2df71250fca48111e965785a111d7b5eb989356dbef785c639efc8e4',
     'e56cb79104c62e5e2bef72f717ec4e009115098d0364bb0cb5dd2ee2a41cd1e0'),
    ('summer-overload', '2.5', 'Akako Hinami', 'Summer Overload', 'license.txt', '© 2022 Akako Hinami', 'by-sa',
     '4ecfa0ab9af121d603a560d68b04b62436c40ec04a9a5e573f7a17e9e954bc92',
     'c4957dedd2ec9bc1a5b96587813ed466ab4d537f5e08e6ca57a4eb76338e81d8'),
)


def fetch(directory, filename, expected_hash, target):
    url = f'https://raw.githubusercontent.com/{REPOSITORY}/{REVISION}/{directory}/{quote(filename)}'
    with urlopen(url, timeout=30) as response:
        data = response.read()
    if hashlib.sha256(data).hexdigest() != expected_hash:
        raise ValueError(f'Unexpected source contents: {url}')
    target.write_bytes(data)


def parse_beginner(path):
    source = re.sub(r'//[^\n]*', '', path.read_text(encoding='utf-8-sig'))
    head, *charts = source.split('#NOTEDATA:;')

    def fields(section):
        return {key: value.strip() for key, value in re.findall(r'#([A-Z]+):([^;]*);', section)}

    song = fields(head)
    selected = [
        chart for chart in map(fields, charts)
        if chart.get('STEPSTYPE') == 'dance-single'
        and chart.get('DIFFICULTY') == 'Beginner'
        and chart.get('CREDIT') == CHART_CREDIT
    ]
    if len(selected) != 1:
        raise ValueError(f'Expected a unique {CHART_CREDIT} Beginner chart: {path.name}')

    chart = {**song, **selected[0]}
    changes = chart['BPMS'].split(',')
    if len(changes) != 1 or any(chart.get(tag) for tag in ('STOPS', 'DELAYS', 'WARPS', 'FAKES')):
        raise ValueError(f'{path.name}: expected constant BPM without timing effects or fake steps')
    beat, bpm = map(Fraction, changes[0].split('='))
    if beat != 0 or bpm <= 0:
        raise ValueError(f'{path.name}: unsupported initial BPM')

    beat_ms = 60_000 / bpm
    offset_ms = Fraction(chart['OFFSET']) * 1000
    notes = []
    # SSC note data uses four beats per comma-delimited block, independent of
    # the time signatures used for musical bar lines in the source chart.
    for i, measure in enumerate(chart['NOTES'].split(',')):
        rows = measure.split()
        for row_index, row in enumerate(rows):
            if not re.fullmatch(r'[01234MLFK]{4}', row) or any(row[lane] not in '01' for lane in LANES):
                raise ValueError(f'{path.name}: unsupported step row {row!r}')
            at_ms = round((4 * i + Fraction(4 * row_index, len(rows))) * beat_ms - offset_ms)
            for lane, action in LANES.items():
                if row[lane] == '1':
                    notes.append([at_ms, action])
    if not notes or notes[0][0] < 0 or any(a[0] >= b[0] for a, b in zip(notes, notes[1:])):
        raise ValueError(f'{path.name}: expected non-negative, exclusive motion cues')
    return song, bpm, notes


def ffmpeg(*args):
    return subprocess.check_output(['ffmpeg', '-v', 'error', '-y', *map(str, args)])


def duration_ms(path):
    # Measure decoded audio so Opus pre-skip and MP3 encoder padding do not
    # extend the game clock. The source and pack audio share sample zero.
    pcm = ffmpeg('-i', path, '-map', '0:a:0', '-ar', SAMPLE_RATE, '-ac', 1, '-f', 's16le', '-')
    return round(Fraction(len(pcm) * 1000, SAMPLE_RATE * 2))


def as_js(songs):
    lines = [
        '// Generated by tools/import-serenity-songs.py from the OutFox Serenity v2.5 release.',
        '// Translated chart data by Daniel Rotwind, CC BY 4.0.',
        '// Source attribution and changes: /assets/audio/serenity/CREDITS.txt',
        'export const SERENITY_SONGS = [',
    ]
    for song, notes in songs:
        lines.append('  {')
        for key, value in song.items():
            lines.append(f'    {key}: {json.dumps(value, ensure_ascii=False)},')
        lines.append('    notes: [')
        lines.extend(f'      [{at_ms}, "{action}"],' for at_ms, action in notes)
        lines.extend(['    ],', '  },'])
    return '\n'.join([*lines, '];', ''])


def main():
    asset_url = '/assets/audio/serenity'
    assets = ROOT / 'src/assets/audio/serenity'
    credits = [
        'OutFox Serenity v2.5 audio and dance-single Beginner stepcharts',
        f'Source release: https://github.com/{REPOSITORY}/releases/tag/v2.5',
        f'Source revision: {REVISION}',
        '',
        f'All three stepcharts are by {CHART_CREDIT} and licensed under CC BY 4.0.',
        f'Chart license: {CHART_LICENSE}',
        f'OutFox chart submission terms: {CHART_TERMS}',
        'Changes to charts: SSC translated to timed left, jump (up) and right cues; down omitted.',
        'Changes to recordings: converted from Opus to 64 kbps MP3; an 8-second, 48 kbps MP3 excerpt is used in song select.',
        'Each packaged recording and its excerpt are provided under the same license as the source recording.',
        '',
    ]
    songs = []
    with tempfile.TemporaryDirectory(prefix='outfox-serenity-') as staging:
        stage = Path(staging)
        for slug, volume, artist, name, notice, recording_credit, license_code, audio_hash, chart_hash in SOURCES:
            directory = quote(f'OutFox Serenity Volume {volume}/{artist} - {name}')
            opus, ssc = stage / f'{slug}.opus', stage / f'{slug}.ssc'
            fetch(directory, name + '.opus', audio_hash, opus)
            fetch(directory, name + '.ssc', chart_hash, ssc)
            song, bpm, notes = parse_beginner(ssc)
            track, preview = stage / f'{slug}.mp3', stage / f'{slug}-preview.mp3'
            encode = ['-map', '0:a:0', '-map_metadata', -1, '-c:a', 'libmp3lame', '-ar', SAMPLE_RATE]
            ffmpeg('-i', opus, *encode, '-b:a', TRACK_BITRATE, track)
            ffmpeg('-i', opus, '-ss', song['SAMPLESTART'], '-t', PREVIEW_SECONDS, *encode, '-b:a', PREVIEW_BITRATE, preview)
            length_ms = duration_ms(opus)
            if duration_ms(track) != length_ms or duration_ms(preview) != PREVIEW_SECONDS * 1000:
                raise ValueError(f'Audio timebase changed during import: {slug}')
            if notes[-1][0] >= length_ms:
                raise ValueError(f'Last chart cue extends beyond the source recording: {slug}')

            songs.append(({
                'id': slug, 'title': song['TITLE'], 'artist': song['ARTIST'], 'bpm': float(bpm),
                'durationMs': length_ms, 'previewMusic': f'{asset_url}/{preview.name}',
                'previewDurationMs': PREVIEW_SECONDS * 1000, 'music': f'{asset_url}/{track.name}',
                'genre': song['GENRE'],
            }, notes))
            source_credit = f'https://github.com/{REPOSITORY}/blob/{REVISION}/{directory}/{notice}'
            credits.extend([
                f'{song["TITLE"]} — {recording_credit} (CC {license_code.upper()} 4.0)',
                f'Recording license: https://creativecommons.org/licenses/{license_code}/4.0/',
                f'Source credits: {source_credit}',
                f'Preview start in original recording: {song["SAMPLESTART"]} seconds',
                '',
            ])
            print(f'{song["TITLE"]}: {len(notes)} motion cues, {length_ms} ms')

        assets.mkdir(parents=True, exist_ok=True)
        for mp3 in stage.glob('*.mp3'):
            shutil.copyfile(mp3, assets / mp3.name)
        (assets / 'CREDITS.txt').write_text('\n'.join(credits), encoding='utf-8')
        (ROOT / 'src/lib/serenity-songs.js').write_text(as_js(songs), encoding='utf-8')


if __name__ == '__main__':
    main()
